CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    rut VARCHAR(9) NOT NULL UNIQUE,
    telefono VARCHAR(20) NOT NULL,
    correo_personal VARCHAR(254) NOT NULL UNIQUE,
    correo_interno VARCHAR(254) NOT NULL UNIQUE,
    pregunta_seguridad VARCHAR(150) NOT NULL,
    respuesta_hash VARCHAR(256) NOT NULL,
    password_hash VARCHAR(256),
    rol_codigo VARCHAR(30),
    activo BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT rol_valido CHECK (rol_codigo IN ('ADMIN','TECNICO','INGENIERO','JEFE_TECNICO','CLIENTE'))
);
CREATE TABLE sesiones (
    token_hash VARCHAR(64) PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    expira_en TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX sesiones_usuario ON sesiones(usuario_id);
CREATE TABLE codigos_recuperacion (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuarios(id),
    codigo_hash VARCHAR(64) NOT NULL,
    expira_en TIMESTAMP WITH TIME ZONE NOT NULL,
    intentos INTEGER NOT NULL DEFAULT 0,
    enviado_en TIMESTAMP WITH TIME ZONE NOT NULL
);
